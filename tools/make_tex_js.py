#!/usr/bin/env python3
"""Packs tex/*.jpg|png into tex.js as data URIs.
Why: WebGL refuses images loaded from file:// pages, so embedding them keeps `open index.html` working.
Run from the project root after changing anything in tex/:  python3 tools/make_tex_js.py
"""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
out = ["// GENERATED by tools/make_tex_js.py. Edit the files in tex/ and re-run, not this file.",
       "// Textures: Solar System Scope (https://www.solarsystemscope.com/textures/), CC BY 4.0, based on NASA data.",
       "const TEX = {"]
for f in sorted((root / "tex").iterdir()):
    mime = {"jpg": "image/jpeg", "png": "image/png"}.get(f.suffix[1:])
    if mime:
        out.append(f"  '{f.stem}': 'data:{mime};base64,{base64.b64encode(f.read_bytes()).decode()}',")
out.append("};")
(root / "tex.js").write_text("\n".join(out) + "\n")
print("wrote tex.js", round((root / "tex.js").stat().st_size / 1024), "KB")
